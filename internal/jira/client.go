package jira

import (
	"bytes"
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"net/http"
	"net/url"
	"strings"
	"time"
)

// Endpoints, request/response formats, and error bodies follow the Jira Data Center REST API:
// https://developer.atlassian.com/server/jira/platform/rest/
const apiPath = "/rest/api/2"

// How long Jira has to start responding to a request
// The download itself isn't limited here, since a shared issue's worklogs can be large,
// so callers limit the whole request with their context instead
const responseTimeout = 30 * time.Second

// Talks to a Jira instance (REST API v2 only)
type Client struct {
	baseURL string
	token   string
	http    *http.Client
}

// Creates a client that authenticates with a personal access token
// Requires: baseURL must be a valid Jira URL, token must be a valid PAT generated by the user
func NewClient(baseURL, token string) *Client {
	// Copy the default transport so proxy and TLS settings still apply
	transport := http.DefaultTransport.(*http.Transport).Clone()
	transport.ResponseHeaderTimeout = responseTimeout
	return &Client{
		baseURL: strings.TrimRight(strings.TrimSpace(baseURL), "/"),
		token:   strings.TrimSpace(token),
		http:    &http.Client{Transport: transport},
	}
}

// Jira's standard error body
type errorBody struct {
	ErrorMessages []string          `json:"errorMessages"`
	Errors        map[string]string `json:"errors"`
}

// Sends a request and decodes the JSON response into out
func (c *Client) do(ctx context.Context, method, path string, body, out any) error {
	var reqBody io.Reader
	if body != nil {
		data, err := json.Marshal(body)
		if err != nil {
			return fmt.Errorf("encode request: %w", err)
		}
		reqBody = bytes.NewReader(data)
	}

	req, err := http.NewRequestWithContext(ctx, method, c.baseURL+apiPath+path, reqBody)
	if err != nil {
		return fmt.Errorf("build request: %w", err)
	}
	req.Header.Set("Authorization", "Bearer "+c.token)
	req.Header.Set("Accept", "application/json")
	if body != nil {
		req.Header.Set("Content-Type", "application/json")
	}

	resp, err := c.http.Do(req)
	if err != nil {
		return c.connectError(ctx, err)
	}
	defer resp.Body.Close()

	if resp.StatusCode < 200 || resp.StatusCode > 299 {
		return statusError(resp)
	}
	if out == nil {
		return nil
	}
	if err := json.NewDecoder(resp.Body).Decode(out); err != nil {
		return fmt.Errorf("decode response: %w", err)
	}
	return nil
}

// Short error for a request that got no response, without the full URL
// Says which time limit was hit so a slow Jira can be told apart from a network problem
func (c *Client) connectError(ctx context.Context, err error) error {
	var ue *url.Error
	switch {
	case ctx.Err() != nil:
		return fmt.Errorf("connect to Jira: the whole request took too long (%w)", ctx.Err())
	case errors.As(err, &ue) && ue.Timeout():
		return fmt.Errorf("connect to Jira: no response within %s", responseTimeout)
	case errors.As(err, &ue):
		return fmt.Errorf("connect to Jira: %w", ue.Err)
	}
	return fmt.Errorf("connect to Jira: %w", err)
}

// Error from Jira that keeps the HTTP status, so callers can tell ex. bad JQL (400) apart
type StatusError struct {
	Code    int
	Message string
}

func (e *StatusError) Error() string { return e.Message }

// Turns a failed response into a short, readable error
func statusError(resp *http.Response) error {
	switch resp.StatusCode {
	case http.StatusUnauthorized:
		return &StatusError{resp.StatusCode, "Authentication failed: check your Jira PAT"}
	case http.StatusForbidden:
		return &StatusError{resp.StatusCode, "Permission denied by Jira"}
	}

	var e errorBody
	if json.NewDecoder(resp.Body).Decode(&e) == nil {
		msgs := e.ErrorMessages
		for field, msg := range e.Errors {
			msgs = append(msgs, field+": "+msg)
		}
		if len(msgs) > 0 {
			return &StatusError{resp.StatusCode, "jira: " + strings.Join(msgs, "; ")}
		}
	}
	return &StatusError{resp.StatusCode, "jira: unexpected status " + resp.Status}
}

// Reports whether err means Jira couldn't understand the request, ex. invalid JQL
func IsBadRequest(err error) bool {
	var se *StatusError
	return errors.As(err, &se) && se.Code == http.StatusBadRequest
}
